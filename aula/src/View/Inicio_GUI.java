    private void CONFIRMAR_BTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CONFIRMAR_BTNActionPerformed
        if (junta.equals("1")){
        ImageIcon icon = new ImageIcon(getClass().getResource("/Image/kratos.jpeg"));
        foto2.setIcon(icon); 
        } else if (junta.equals("2")){
        ImageIcon icon = new ImageIcon(getClass().getResource("/Image/bolsonaro.jpg"));
        foto2.setIcon(icon); 
        } else if (junta.equals("3")){
        ImageIcon icon = new ImageIcon(getClass().getResource("/Image/lula.jpg"));
        foto2.setIcon(icon); 
        } else {
        javax.swing.JOptionPane.showMessageDialog(null, "Candidato inválido");
        return;
        }
        
        String op = javax.swing.JOptionPane.showInputDialog(null, "Digite 1 para confirmar ou 2 para recusar:");

    
    if (op != null && op.equals("1")) {
        
        if (junta.equals("1")) {
            cand1++;
        } else if (junta.equals("2")) {
            cand2++;
        } else if (junta.equals("3")) {
            cand3++;
        }

        javax.swing.JOptionPane.showMessageDialog(null, "Voto confirmado");

        junta = "";
        campo.setText("");
        foto2.setIcon(null);
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(null, "Voto cancelado");
        junta = "";
        campo.setText("");
        foto2.setIcon(null);
    }
        
        
            
    }//GEN-LAST:event_CONFIRMAR_BTNActionPerformed

